# First N Characters

# Problem Statement:

# Given a string and a number N, print the first N characters of the string.

#

# Input:

# First line contains a string.

# Second line contains an integer N.

#

# Output:

# Print the first N characters.

#

# Example:

# Input:

# Programming

# 4

#

# Output:

# Prog

a = input()
n = int(input())
print(a[:n])
